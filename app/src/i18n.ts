function savedLang(): Lang {
  try {
    const v = localStorage.getItem('lang')
    if (v === 'ru' || v === 'kz') return v
  } catch { /* storage unavailable */ }
  return 'ru'
}

i18n.use(initReactI18next).init({
  resources: { ru: { translation: { ...ru, ...ruCalc, ...ruMore } }, kz: { translation: { ...kz, ...kzCalc, ...kzMore } } },
  lng: savedLang(),
  fallbackLng: 'ru',
  interpolation: { escapeValue: false },
  returnObjects: true,
})

i18n.on('languageChanged', (lng) => {
  document.documentElement.lang = lng === 'kz' ? 'kk' : 'ru'
  try { localStorage.setItem('lang', lng) } catch { /* storage unavailable */ }
})
document.documentElement.lang = i18n.language === 'kz' ? 'kk' : 'ru'

export default i18n
